# ============================================================

def denoise_video_with_model(
    model_path,
    test_item,
    output_video_path,
    use_5frames=True,
    radius=2,
):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print("\nInference device:", device)

    frames, fps = load_video_gray(test_item["video_path"], normalize=True)
    T, H, W = frames.shape

    in_ch = 5 if use_5frames else 1

    model = SmallUNet(
        in_ch=in_ch,
        out_ch=1,
        features=(32, 64, 128)
    ).to(device)

    model.load_state_dict(torch.load(model_path, map_location=device))
    model.eval()

    denoised_frames = []

    with torch.no_grad():
        for t in tqdm(range(T), desc="Denoising test video"):
            if use_5frames:
                idxs = []

                for dt in range(-radius, radius + 1):
                    idx = t + dt
                    idx = max(0, min(T - 1, idx))
                    idxs.append(idx)

                input_frames = frames[idxs]
            else:
                input_frames = frames[t:t + 1]

            x = torch.from_numpy(input_frames.astype(np.float32))[None, :, :, :]
            x = x.to(device)

            y = model(x)
            y = y[0, 0].detach().cpu().numpy()

            y_u8 = np.clip(y * 255.0, 0, 255).astype(np.uint8)
            denoised_frames.append(y_u8)

    output_video_path = Path(output_video_path)
    output_video_path.parent.mkdir(parents=True, exist_ok=True)

    fourcc = cv2.VideoWriter_fourcc(*"XVID")

    writer = cv2.VideoWriter(
        str(output_video_path),
        fourcc,
        fps,
        (W, H),
        isColor=False
    )

    for frame_u8 in denoised_frames:
        writer.write(frame_u8)

    writer.release()

    print("\nDenoised test video saved to:")
    print(output_video_path)


