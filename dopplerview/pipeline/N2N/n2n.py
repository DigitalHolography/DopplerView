def train_n2n_model(
    train_dataset,
    val_dataset,
    use_5frames=True,
    batch_size=2,
    epochs=40,
    lr=1e-4,
    save_path="best_n2n_model.pth",
):
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print("\nDevice:", device)

    in_ch = 5 if use_5frames else 1

    model = SmallUNet(
        in_ch=in_ch,
        out_ch=1,
        features=(32, 64, 128)
    ).to(device)

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=lr,
        weight_decay=1e-5
    )

    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=0,
        pin_memory=True
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=0,
        pin_memory=True
    )

    best_val = float("inf")

    for epoch in range(1, epochs + 1):
        # -------------------------
        # train
        # -------------------------
        model.train()
        train_losses = []

        pbar = tqdm(train_loader, desc=f"Epoch {epoch}/{epochs} [train]")

        for input_tensor, target_tensor, input_center, vessel_mask, background_mask in pbar:
            input_tensor = input_tensor.to(device)
            target_tensor = target_tensor.to(device)
            input_center = input_center.to(device)
            vessel_mask = vessel_mask.to(device)
            background_mask = background_mask.to(device)

            output = model(input_tensor)

            loss = n2n_vessel_background_loss(
                output=output,
                target=target_tensor,
                input_center=input_center,
                vessel_mask=vessel_mask,
                background_mask=background_mask,
            )

            optimizer.zero_grad()
            loss.backward()
            optimizer.step()

            train_losses.append(loss.item())
            pbar.set_postfix(loss=float(np.mean(train_losses)))

        mean_train = float(np.mean(train_losses))

        # -------------------------
        # validation
        # -------------------------
        model.eval()
        val_losses = []

        with torch.no_grad():
            pbar_val = tqdm(val_loader, desc=f"Epoch {epoch}/{epochs} [val]")

            for input_tensor, target_tensor, input_center, vessel_mask, background_mask in pbar_val:
                input_tensor = input_tensor.to(device)
                target_tensor = target_tensor.to(device)
                input_center = input_center.to(device)
                vessel_mask = vessel_mask.to(device)
                background_mask = background_mask.to(device)

                output = model(input_tensor)

                loss = n2n_vessel_background_loss(
                    output=output,
                    target=target_tensor,
                    input_center=input_center,
                    vessel_mask=vessel_mask,
                    background_mask=background_mask,
                )

                val_losses.append(loss.item())
                pbar_val.set_postfix(loss=float(np.mean(val_losses)))

        mean_val = float(np.mean(val_losses))

        print(
            f"Epoch {epoch}/{epochs} | "
            f"train loss = {mean_train:.6f} | "
            f"val loss = {mean_val:.6f}"
        )

        if mean_val < best_val:
            best_val = mean_val
            torch.save(model.state_dict(), save_path)
            print("Saved best model:", save_path)

    return model


